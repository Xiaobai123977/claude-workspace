const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const assert = require('node:assert/strict')
const { SettingsService } = require('../electron/settings.cjs')
const cli = require('../electron/claude.cjs')
const { JsonLines, TurnAccumulator } = require('../electron/stream.cjs')
const root = fs.mkdtempSync(path.join(os.tmpdir(),'claude-settings-real-'))
const cwd = path.join(root,'project');fs.mkdirSync(cwd)
const service = new SettingsService({userData:path.join(root,'app'),preferences:()=>({}),secureStorage:{isEncryptionAvailable:()=>false}})
const before=service.read(cwd)
service.save(cwd,{scope:'app',revision:before.sources.app.revision,changes:{language:'中文',effortLevel:'low','permissions.allow':['Read']}})
const runtime=service.prepareRuntime(cwd)
const args=[...cli.buildTurn({cwd,model:'',effort:'',permission:'plan'}, {},[],runtime),'--tools','','--max-turns','1','--no-session-persistence']
assert.ok(!args.includes('--model'));assert.ok(!args.includes('--effort'))
assert.equal(JSON.parse(fs.readFileSync(runtime.settingsPath)).language,'中文')
const message={text:'',tools:[],status:'running'}, accumulator=new TurnAccumulator(message)
const child=cli.launch(cli.resolveClaude(),args,cwd,runtime.env)
let stderr=''
const parser=new JsonLines(e=>accumulator.consume(e))
child.stdout.on('data',chunk=>parser.push(chunk));child.stderr.on('data',chunk=>stderr+=chunk.toString())
child.stdin.on('error',()=>{});child.stdin.end('这是设置接入验证。不要调用工具，只回复：设置接入成功。\n')
const timer=setTimeout(()=>cli.terminate(child),60000)
child.on('error',()=>{})
child.on('close',code=>{
  clearTimeout(timer);parser.end();accumulator.finish(code,stderr);runtime.cleanup()
  try{
    assert.equal(message.status,'done',message.error);assert.match(message.text,/设置接入成功/)
    const after=service.read(cwd)
    for(const key of ['user','project','local','managed'])assert.equal(after.sources[key].revision,before.sources[key].revision)
    console.log('Real Claude settings smoke passed: scoped --settings file, inherited model/effort, native config unchanged, runtime cleanup.')
    console.log(JSON.stringify({model:message.model,response:message.text,version:process.version}))
  }catch(e){console.error(e.message);process.exitCode=1}
})
