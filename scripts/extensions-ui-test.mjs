// Real public catalogs and native CLI; all writes use an isolated config profile.
import { _electron as electron } from 'playwright'
import { createRequire } from 'node:module'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url), root = path.resolve(import.meta.dirname, '..')
const base = fs.mkdtempSync(path.join(fs.realpathSync.native(os.tmpdir()), 'claude-extensions-ui-'))
const cwd = path.join(base, 'project'), config = path.join(base, 'config'), userData = path.join(base, 'app')
for (const dir of [cwd, config, userData, path.join(cwd, '.claude/skills/gui-local')]) fs.mkdirSync(dir, { recursive: true })
fs.writeFileSync(path.join(cwd, '.claude/skills/gui-local/SKILL.md'), '---\nname: gui-local\ndescription: Isolated UI sample\n---\n# Sample skill\n\nOnly for UI integration tests.\n')
fs.writeFileSync(path.join(cwd, '.claude/settings.local.json'), JSON.stringify({ preserveUnknown: true }))
const id = 'extensions-ui', preferences = { cliPath: require('../electron/claude.cjs').resolveClaude(), configDir: config, fontSize: '14', model: '', effort: '', permission: '', allowedTools: '', disallowedTools: '' }
fs.writeFileSync(path.join(userData, 'workspace.json'), JSON.stringify({ version: 1, preferences, activeId: id, sessions: [{ id, cwd, title: '扩展管理验证', model: '', effort: '', permission: '', createdAt: Date.now(), updatedAt: Date.now(), archived: false, messages: [] }] }))
const env = { ...process.env, CLAUDE_GUI_DATA_DIR: userData, CLAUDE_CONFIG_DIR: config, CLAUDE_GUI_TEST_MANAGED_FILE: path.join(base, 'managed.json') }; delete env.ELECTRON_RUN_AS_NODE
const app = await electron.launch({ executablePath: require('electron'), args: [root], env })
try {
  const page = await app.firstWindow(); page.setDefaultTimeout(180000)
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.getByRole('button', { name: '扩展', exact: true }).click()
  await page.locator('.extensions-layout').waitFor()
  const nav = page.getByRole('navigation', { name: '扩展分类' })
  await page.getByText('还没有安装插件', { exact: true }).waitFor()
  await nav.getByRole('button', { name: 'Skills', exact: true }).click()
  await page.getByLabel('gui-local 调用方式', { exact: true }).selectOption('user-invocable-only')
  await page.getByRole('status').waitFor()
  assert.equal(JSON.parse(fs.readFileSync(path.join(cwd, '.claude/settings.local.json'))).skillOverrides['gui-local'], 'user-invocable-only')
  await page.getByRole('button', { name: '查看内容', exact: true }).click()
  await page.getByRole('dialog').getByText('Sample skill', { exact: true }).waitFor()
  await page.getByRole('button', { name: '关闭扩展详情', exact: true }).click()
  await nav.getByRole('button', { name: '市场', exact: true }).click()
  await page.locator('.extension-tile').first().waitFor()
  await page.screenshot({ path: path.join(root, 'artifacts/extensions-market-official.png') })
  await page.getByRole('button', { name: 'Anthropic Skills', exact: true }).click()
  await page.getByRole('button', { name: '查看 frontend-design', exact: true }).waitFor()
  await page.getByRole('button', { name: '查看 frontend-design', exact: true }).click()
  await page.getByRole('dialog').locator('.markdown').waitFor()
  await page.screenshot({ path: path.join(root, 'artifacts/extensions-skill-preview.png') })
  await page.getByRole('button', { name: '关闭扩展详情', exact: true }).click()
  await page.getByRole('button', { name: 'Superpowers 社区', exact: true }).click()
  await page.getByRole('button', { name: '查看 elements-of-style', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '安装', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await nav.getByRole('button', { name: '插件', exact: true }).click()
  const plugin = page.locator('.extension-row').filter({ hasText: 'elements-of-style' })
  await plugin.waitFor()
  await plugin.getByRole('button', { name: '停用', exact: true }).click()
  await plugin.getByRole('button', { name: '启用', exact: true }).waitFor()
  await plugin.getByRole('button', { name: '启用', exact: true }).click()
  await plugin.getByRole('button', { name: '停用', exact: true }).waitFor()
  await page.screenshot({ path: path.join(root, 'artifacts/extensions-installed.png') })
  await plugin.getByRole('button', { name: '卸载', exact: true }).click()
  await page.getByRole('button', { name: '确认卸载', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.getByText('还没有安装插件', { exact: true }).waitFor()
  await nav.getByRole('button', { name: 'MCP', exact: true }).click()
  await page.getByRole('button', { name: '手动添加', exact: true }).click()
  await page.getByLabel('MCP 服务器名称', { exact: true }).fill('ui-test-mcp')
  await page.getByLabel('MCP 连接配置', { exact: true }).fill(JSON.stringify({ type: 'http', url: 'http://127.0.0.1:31415/mcp' }, null, 2))
  await page.getByRole('button', { name: '添加服务器', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.locator('.extension-row').filter({ hasText: 'ui-test-mcp' }).waitFor()
  await page.getByRole('button', { name: '停用', exact: true }).click()
  await page.getByRole('button', { name: '启用', exact: true }).click()
  await page.getByRole('button', { name: '停用', exact: true }).waitFor()
  await page.screenshot({ path: path.join(root, 'artifacts/extensions-mcp.png') })
  await page.getByRole('button', { name: '移除', exact: true }).click()
  await page.getByRole('button', { name: '确认移除', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  await page.getByText('还没有配置 MCP 服务器', { exact: true }).waitFor()
  await page.getByRole('button', { name: '浏览 Registry', exact: true }).click()
  await page.locator('.extension-tile').first().waitFor()
  await page.screenshot({ path: path.join(root, 'artifacts/extensions-market-mcp.png') })
  await page.getByRole('button', { name: '返回聊天', exact: true }).click()
  await page.getByRole('textbox', { name: '消息输入' }).fill('/gui-local')
  await page.getByRole('option').filter({ hasText: '/gui-local' }).waitFor()
  assert.equal(JSON.parse(fs.readFileSync(path.join(cwd, '.claude/settings.local.json'))).preserveUnknown, true)
  assert.deepEqual(errors, [])
  console.log('Extensions UI passed: public markets, skill preview/visibility/slash refresh, real public plugin install/enable/disable/uninstall, real MCP add/remove, config preservation.')
} finally { await app.close(); console.log('Isolated UI profile:', base) }
