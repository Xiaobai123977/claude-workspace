import { _electron as electron } from 'playwright'
import { createRequire } from 'node:module'
import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url)
const root = path.resolve(import.meta.dirname, '..')
const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'claude-gui-ui-'))
const id = 'local-test-session'
const preferences = { cliPath: path.join(root, 'tests/fake-claude.cjs'), model: 'sonnet', effort: 'medium', permission: 'default', allowedTools: '', disallowedTools: '' }
fs.writeFileSync(path.join(dataDir, 'workspace.json'), JSON.stringify({ version: 1, preferences, activeId: id, sessions: [{ id, cwd: root, title: '新聊天', model: 'sonnet', effort: 'medium', permission: 'default', messages: [], createdAt: Date.now(), updatedAt: Date.now(), archived: false }] }))
fs.mkdirSync(path.join(root, 'artifacts'), { recursive: true })
const env = { ...process.env, CLAUDE_GUI_DATA_DIR: dataDir,CLAUDE_CONFIG_DIR:path.join(dataDir,'native-profile') }; delete env.ELECTRON_RUN_AS_NODE
const launch = () => electron.launch({ executablePath: require('electron'), args: [root], env })
let app = await launch()
const errors = []
try {
  let page = await app.firstWindow()
  page.on('pageerror', e => errors.push(e.message))
  await page.getByRole('textbox', { name: '消息输入' }).waitFor()
  await page.screenshot({ path: path.join(root, 'artifacts/home.png') })
  const input = page.getByRole('textbox', { name: '消息输入' })
  await input.fill('/')
  await page.getByRole('listbox', { name: '命令菜单' }).waitFor()
  await page.screenshot({ path: path.join(root, 'artifacts/commands.png') })
  await input.fill('@README')
  await page.getByRole('listbox', { name: '项目文件' }).getByRole('option').first().waitFor()
  await input.press('Enter')
  await page.locator('.attachment').waitFor()
  await input.fill('你好，请检查项目')
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await page.getByText('最终输出已完整接收。', { exact: false }).waitFor()
  await page.waitForFunction(() => document.querySelectorAll('.working').length === 0)
  assert.equal(await page.locator('.markdown').filter({ hasText: '你好，我已连接到 Claude 工作区。' }).count(), 1)
  await page.getByRole('button', { name: /Read 已完成/ }).click()
  await page.getByText('项目文件已读取', { exact: true }).waitFor()
  await input.fill('继续处理')
  await input.press('Enter')
  await page.getByText('会话已恢复，继续处理。', { exact: false }).waitFor()
  await page.waitForFunction(() => document.querySelectorAll('.working').length === 0)
  await page.screenshot({ path: path.join(root, 'artifacts/chat.png') })
  // Import clipboard-format image through the same bridge as the composer.
  const attachment = await page.evaluate(async () => (await window.workspace.importFiles([{ name: 'clipboard.png', data: 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Wl6z1sAAAAASUVORK5CYII=' }]))[0])
  await page.evaluate(async ({ id, attachmentId }) => { await window.workspace.send(id, '查看图片', [attachmentId]) }, { id, attachmentId: attachment.id })
  await page.getByText('已收到图片文件引用。', { exact: false }).waitFor()
  await page.waitForFunction(() => document.querySelectorAll('.working').length === 0)
  await input.fill('等待停止')
  await input.press('Enter')
  await page.getByRole('button', { name: '停止执行', exact: true }).waitFor()
  await page.getByRole('button', { name: '停止执行', exact: true }).click()
  await page.getByText('已停止 · 已完成的工作与会话会保留').waitFor()
  await input.fill('触发失败')
  await input.press('Enter')
  await page.getByText('测试：结构化调用失败', { exact: true }).waitFor()
  await page.getByRole('button', { name: '模型与推理强度' }).click()
  await page.locator('.model-menu').getByRole('button', { name: 'Claude Opus' }).click()
  const saved = await page.evaluate(() => window.workspace.get())
  assert.equal(saved.sessions[0].model, 'opus')
  assert.match(saved.sessions[0].nativeId, /^[0-9a-f-]{36}$/)
  assert.equal(saved.sessions[0].messages.filter(m => m.status === 'stopped').length, 1)
  await app.close()
  app = await launch(); page = await app.firstWindow()
  await page.getByText('会话已恢复，继续处理。', { exact: false }).waitFor()
  const restored = await page.evaluate(() => window.workspace.get())
  assert.equal(restored.sessions[0].nativeId, saved.sessions[0].nativeId)
  assert.equal(restored.sessions[0].messages.length, saved.sessions[0].messages.length)
  const forked = await page.evaluate(() => window.workspace.fork('local-test-session'))
  assert.equal(forked.messages.length, saved.sessions[0].messages.length)
  const previousResponses = forked.messages.filter(m => m.role === 'assistant').length
  await page.evaluate(async id => { await window.workspace.send(id, '验证聊天分支', []) }, forked.id)
  await page.locator('.message.assistant').nth(previousResponses).waitFor()
  await page.waitForFunction(() => document.querySelectorAll('.working').length === 0)
  const branched = await page.evaluate(() => window.workspace.get())
  assert.notEqual(branched.sessions[0].nativeId, saved.sessions[0].nativeId)
  assert.equal(branched.sessions.find(s => s.id === id).nativeId, saved.sessions[0].nativeId)
  assert.deepEqual(errors, [])
  console.log('UI integration passed: file menu, stream dedupe, tool result, resume, images, stop, errors, model change, persistence, independent fork. Screenshots: artifacts/')
} finally { await app.close(); console.log(`Isolated test data: ${dataDir}`) }
