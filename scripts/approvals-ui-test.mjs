import { _electron as electron } from 'playwright'
import { createRequire } from 'node:module'
import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import assert from 'node:assert/strict'
const require = createRequire(import.meta.url), root = path.resolve(import.meta.dirname, '..')
const base = fs.mkdtempSync(path.join(fs.realpathSync.native(os.tmpdir()), 'claude-approvals-ui-'))
const dataDir = path.join(base, 'app'), cwd = path.join(base, 'project'), config = path.join(base, 'config')
for (const dir of [dataDir, cwd, config]) fs.mkdirSync(dir)
const id = 'approval-session'
const prefs = { cliPath: path.join(root, 'tests/fake-claude.cjs'), configDir: config, fontSize: '14', model: 'sonnet', effort: 'low', permission: 'default', allowedTools: '', disallowedTools: '' }
fs.writeFileSync(path.join(dataDir, 'workspace.json'), JSON.stringify({ version: 1, preferences: prefs, activeId: id, sessions: [{ id, cwd, title: '审批交互测试', createdAt: Date.now(), updatedAt: Date.now(), archived: false, model: 'sonnet', effort: 'low', permission: 'default', messages: [] }] }))
const env = { ...process.env, CLAUDE_GUI_DATA_DIR: dataDir,CLAUDE_CONFIG_DIR:path.join(dataDir,'native-profile') }; delete env.ELECTRON_RUN_AS_NODE
const launch = () => electron.launch({ executablePath: require('electron'), args: [root], env })
let app = await launch(), page = await app.firstWindow();page.setDefaultTimeout(15000)
const errors = []; page.on('pageerror', e => errors.push(e.message))
const fixtureFile = path.join(cwd, 'approval-fixture.txt')
async function send(text) {
  await page.getByRole('textbox', { name: '消息输入' }).fill(text)
  await page.getByRole('button', { name: '发送消息', exact: true }).click()
  await page.waitForFunction(()=>document.querySelector('textarea[aria-label="消息输入"]').value==='')
}
async function idle() { await page.waitForFunction(() => !document.querySelector('.working'),undefined,{timeout:15000}) }
async function answer(text) { await page.locator('.approval-card').getByRole('button', { name: text, exact: true }).click(); await idle() }
try {
  await page.getByRole('textbox', { name: '消息输入' }).waitFor()
  await send('审批写入')
  await page.getByRole('region', { name: '允许这次操作吗？' }).waitFor()
  assert.equal(fs.existsSync(fixtureFile), false)
  await page.screenshot({ path: path.join(root, 'artifacts/approval-tool.png') })
  const firstRequest = await page.evaluate(() => window.workspace.get().then(s => s.sessions[0].messages.at(-1).approvals[0].id))
  await answer('允许一次'); assert.equal(fs.readFileSync(fixtureFile, 'utf8'), 'APPROVED_FIXTURE')
  const stale = await page.evaluate(async ({ id, requestId }) => { try { await window.workspace.answer(id, requestId, { action: 'allow' }); return false } catch { return true } }, { id, requestId: firstRequest })
  assert.equal(stale, true)
  fs.unlinkSync(fixtureFile)
  await send('审批拒绝')
  await page.locator('.approval-reject summary').click()
  await page.getByLabel('拒绝原因', { exact: true }).fill('保留原文件，先给我方案')
  await answer('拒绝')
  assert.equal(fs.existsSync(fixtureFile), false)
  await page.getByText('操作已拒绝：保留原文件，先给我方案', { exact: true }).waitFor()
  await send('提问选择')
  const card = page.locator('.approval-card')
  await card.getByRole('radio', { name: '详细 包含解释' }).check()
  await card.getByRole('checkbox', { name: '代码', exact: true }).check()
  await card.getByRole('checkbox', { name: '测试', exact: true }).check()
  await page.screenshot({ path: path.join(root, 'artifacts/approval-question.png') })
  await answer('提交回答')
  let state = await page.evaluate(() => window.workspace.get())
  assert.deepEqual(state.sessions[0].messages.at(-1).approvals[0].answer, { '选择输出风格': '详细', '选择要包含的内容': ['代码', '测试'] })
  await send('提问自由回答')
  await page.getByLabel('选择输出风格：其他回答').fill('只提供可直接运行的示例')
  await card.getByRole('checkbox', { name: '代码', exact: true }).check()
  await answer('提交回答')
  state = await page.evaluate(() => window.workspace.get())
  assert.equal(state.sessions[0].messages.at(-1).approvals[0].answer['选择输出风格'], '只提供可直接运行的示例')
  await page.evaluate(id => window.workspace.update(id, { permission: 'plan' }), id)
  await send('确认计划，先退回')
  await card.getByText('实施计划', { exact: true }).waitFor()
  await page.screenshot({ path: path.join(root, 'artifacts/approval-plan.png') })
  await answer('退回修改')
  await send('确认计划，再批准')
  await answer('批准并继续')
  state = await page.evaluate(() => window.workspace.get())
  assert.equal(state.sessions[0].permission, 'default')
  await send('审批禁止记住')
  await card.waitFor()
  assert.equal(await card.getByRole('button', { name: '本会话允许此类操作', exact: true }).count(), 0)
  const cancelledId = await page.evaluate(() => window.workspace.get().then(s => s.sessions[0].messages.at(-1).approvals[0].id))
  await page.getByRole('button', { name: '停止执行', exact: true }).click(); await idle()
  assert.equal(await card.count(), 0)
  state = await page.evaluate(() => window.workspace.get())
  assert.equal(state.sessions[0].messages.at(-1).status, 'stopped')
  assert.equal(state.sessions[0].messages.at(-1).approvals[0].status, 'cancelled')
  assert.equal(fs.existsSync(fixtureFile), false)
  const cancelled = await page.evaluate(async ({ id, requestId }) => { try { await window.workspace.answer(id, requestId, { action: 'allow' }); return false } catch { return true } }, { id, requestId: cancelledId })
  assert.equal(cancelled, true)
  await send('会话授权第一次'); await answer('本会话允许此类操作')
  fs.unlinkSync(fixtureFile)
  await send('会话授权第二次'); await idle()
  assert.equal(fs.existsSync(fixtureFile), true)
  assert.equal(await card.count(), 0)
  await send('等待审批取消')
  // Already remembered Write requests execute directly in this session.
  await idle()
  const other = await page.evaluate(cwd => window.workspace.create(cwd), cwd)
  await send('等待审批取消')
  await card.waitFor()
  await page.evaluate(id => window.workspace.select(id), id)
  assert.equal(await card.count(), 0)
  await page.evaluate(otherId => window.workspace.select(otherId), other.id)
  await card.waitFor()
  await page.getByRole('button', { name: '停止执行', exact: true }).click(); await idle()
  assert.deepEqual(errors, [])
  assert.equal(fs.existsSync(path.join(cwd, '.claude/settings.local.json')), false)
  await app.close(); app = await launch(); page = await app.firstWindow()
  await page.getByRole('textbox', { name: '消息输入' }).waitFor()
  assert.equal(await page.locator('.approval-card').count(), 0)
  console.log('Approvals UI passed: allow/deny, denial reason, stale reply rejection, multi-select/free text, plan deny/approve, suppression, stop/cancel, remembered session rules, session isolation, restart.')
} finally { await app.close(); console.log('Isolated test data:', base) }
