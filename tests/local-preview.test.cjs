const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),os=require('node:os')
const {pathToFileURL}=require('node:url'),{localFile,startLocalPreview}=require('../electron/local-preview.cjs')
test('local HTML preview resolves file URLs and serves module assets while enforcing the project boundary',async t=>{
  const temp=fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()),'claude-local-web-')),root=path.join(temp,'project');fs.mkdirSync(root)
  fs.writeFileSync(path.join(root,'中文 页面.html'),'<h1>Local HTML</h1>');fs.writeFileSync(path.join(root,'index.html'),'index');fs.writeFileSync(path.join(root,'style.css'),'h1{color:red}');fs.writeFileSync(path.join(root,'app.mjs'),'export const value=1');fs.writeFileSync(path.join(root,'.env'),'PRIVATE');fs.writeFileSync(path.join(temp,'outside.html'),'OUTSIDE')
  const preview=await startLocalPreview(root);t.after(()=>{preview.close();fs.rmSync(temp,{recursive:true,force:true})})
  const local=localFile(root,pathToFileURL(path.join(root,'中文 页面.html')).href+'?test=1#heading')
  assert.equal(local.search,'?test=1');assert.equal(local.hash,'#heading')
  assert.match(await(await fetch(preview.url(local.file))).text(),/Local HTML/)
  const base=new URL(preview.url(local.file)).origin
  assert.equal(await(await fetch(base+'/')).text(),'index')
  assert.match((await fetch(base+'/app.mjs')).headers.get('content-type'),/javascript/)
  assert.equal((await fetch(base+'/.env')).status,403)
  assert.equal((await fetch(base+'/%2e%2e%5coutside.html')).status,403)
  assert.equal((await fetch(base+'/style.css',{headers:{Origin:'https://evil.invalid'}})).status,403)
  assert.throws(()=>localFile(root,pathToFileURL(path.join(temp,'outside.html')).href),/项目目录/)
  assert.throws(()=>localFile(root,pathToFileURL(path.join(root,'app.mjs')).href),/HTML/)
  assert.throws(()=>localFile(root,'file://remote/share/page.html'),/本地 HTML/)
})
