test('resume, explicit modes and outside-file directories are passed as argument arrays', () => {
  const cwd = path.resolve('project'), outside = path.resolve('other', 'file with spaces.txt')
  const args = buildTurn({ cwd, permission: 'plan', nativeId: 'uuid', model: 'sonnet', effort: 'high' }, {}, [{ kind: 'file', path: outside }])
  assert.equal(args[args.indexOf('--resume') + 1], 'uuid')
  assert.equal(args[args.indexOf('--add-dir') + 1], path.dirname(outside))
  assert.ok(!args.includes('--dangerously-skip-permissions'))
  assert.match(makeInput('解释 @a.txt', [{ kind: 'file', path: outside }]), /file with spaces/)
  assert.equal(isInside(cwd, path.resolve(cwd, '..', 'project2')), false)
  const fork = buildTurn({ cwd, permission: 'default', nativeId: 'uuid', forkPending: true }, {})
  assert.ok(fork.includes('--fork-session'))
  const bridged = buildTurn({cwd, providerId:'connection', effort:'none'}, {})
  assert.ok(!bridged.includes('--effort'))
})

