const test = require('node:test')
const assert = require('node:assert/strict')
const { JsonLines, TurnAccumulator } = require('../electron/stream.cjs')
const { buildTurn, makeInput, isInside } = require('../electron/claude.cjs')
const path = require('node:path')
const message = () => ({ text: '', tools: [], status: 'running' })
const stream = event => ({ type: 'stream_event', event })

test('child results and tools never replace the main result and child failures remain visible',()=>{
  const m=message(),turn=new TurnAccumulator(m)
  turn.consume({type:'assistant',parent_tool_use_id:'agent',message:{id:'child',content:[{type:'tool_use',id:'child-read',name:'Read',input:{file_path:'a'}}]}})
  turn.consume({type:'user',parent_tool_use_id:'agent',message:{content:[{type:'tool_result',tool_use_id:'child-read',content:'child-only file'}]}})
  turn.consume({type:'result',parent_tool_use_id:'agent',subtype:'error',is_error:true,result:'child-only failure'})
  assert.equal(turn.result,null);assert.equal(m.tools.length,0)
  turn.consume({type:'assistant',message:{id:'parent',content:[{type:'text',text:'latest main answer'}]}})
  turn.consume({type:'result',subtype:'success',result:'latest main answer'});turn.finish(0)
  assert.equal(m.text,'latest main answer');assert.equal(m.status,'done');assert.equal(m.subagents[0].status,'error')
  assert.equal(m.subagents[0].tools[0].output,'child-only file')
})
test('subagent output stays separate, task lifecycle and structured results are retained',()=>{
  const m=message(),turn=new TurnAccumulator(m)
  turn.consume({type:'assistant',parent_tool_use_id:'agent1',message:{id:'child',content:[{type:'text',text:'Child output'}]}})
  turn.consume({type:'assistant',message:{id:'main',content:[{type:'text',text:'Main output'}]}})
  turn.consume({type:'system',subtype:'task_started',task_id:'task1',description:'Review'})
  turn.consume({type:'system',subtype:'task_notification',task_id:'task1',status:'completed',summary:'Done'})
  turn.consume({type:'result',subtype:'success',structured_output:{ok:true}});turn.finish(0)
  assert.equal(m.text,'Main output');assert.equal(m.subagents[0].text,'Child output');assert.equal(m.tasks[0].status,'completed');assert.deepEqual(m.structured,{ok:true})
})

test('JSON lines survive every possible byte boundary including Chinese UTF-8 and an unterminated final record', () => {
  const input = Buffer.from('{"text":"中文输入"}\r\n{"end":true}')
  for (let at = 0; at <= input.length; at++) {
    const events = [], parser = new JsonLines(e => events.push(e))
    parser.push(input.subarray(0, at)); parser.push(input.subarray(at)); parser.end()
    assert.deepEqual(events, [{ text: '中文输入' }, { end: true }])
  }
})
test('stream and reindexed snapshots do not duplicate text; messages after result are retained', () => {
  const m = message(), turn = new TurnAccumulator(m)
  turn.consume(stream({ type: 'message_start', message: { id: 'one' } }))
  turn.consume(stream({ type: 'content_block_delta', delta: { type: 'text_delta', text: '你好' } }))
  turn.consume({ type: 'assistant', message: { id: 'one', content: [{ type: 'text', text: '你好世界' }] } })
  turn.consume({ type: 'result', subtype: 'success', result: '你好世界', usage: { output_tokens: 4 } })
  assert.equal(m.status, 'running')
  turn.consume({ type: 'assistant', message: { id: 'two', content: [{ type: 'text', text: '后台工作完成' }] } })
  turn.finish(0)
  assert.equal(m.text, '你好世界\n\n后台工作完成'); assert.equal(m.status, 'done')
})
test('tool arguments and results reconcile by call ID even across model messages', () => {
  const m = message(), turn = new TurnAccumulator(m)
  turn.consume(stream({ type: 'content_block_start', index: 0, content_block: { type: 'tool_use', id: 'call1', name: 'Read', input: {} } }))
  turn.consume(stream({ type: 'content_block_delta', index: 0, delta: { type: 'input_json_delta', partial_json: '{"file_path":"a.md"}' } }))
  turn.consume({ type: 'assistant', message: { id: 'toolMessage', content: [{ type: 'tool_use', id: 'call1', name: 'Read', input: { file_path: 'a.md' } }] } })
  turn.consume({ type: 'user', message: { content: [{ type: 'tool_result', tool_use_id: 'call1', content: [{ type: 'text', text: '内容' }] }] } })
  assert.equal(m.tools.length, 1); assert.equal(m.tools[0].output, '内容'); assert.equal(m.tools[0].status, 'done')
})
